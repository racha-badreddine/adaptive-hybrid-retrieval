# ── NDCG@10 (fast, graded relevance, matches pytrec_eval formula) ─────────────

def _ndcg_at10(qrel: Dict[str, int], result: Dict[str, float]) -> float:
    """
    NDCG@10 using standard graded-relevance formula.
    Matches pytrec_eval / BEIR's evaluate() output for the common case.
    Uses: DCG = sum (2^rel - 1) / log2(rank+1) for rank 1..10.
    """
    ranked = sorted(result.items(), key=lambda x: x[1], reverse=True)[:10]
    dcg = 0.0
    for rank, (doc_id, _) in enumerate(ranked, start=1):
        rel = qrel.get(doc_id, 0)
        if rel > 0:
            dcg += (2 ** rel - 1) / math.log2(rank + 1)

    ideal_rels = sorted(qrel.values(), reverse=True)[:10]
    idcg = sum(
        (2 ** r - 1) / math.log2(i + 2)
        for i, r in enumerate(ideal_rels)
        if r > 0
    )
    return dcg / idcg if idcg > 0 else 0.0


def _per_query_ndcg(
    qrels: Dict[str, Dict[str, int]],
    fused:  Dict[str, Dict[str, float]],
) -> Dict[str, float]:
    return {
        qid: _ndcg_at10(qrels[qid], fused[qid])
        for qid in fused
        if qid in qrels
    }


# ── Data loading ──────────────────────────────────────────────────────────────

def load_v3_df(enc_cfg: dict, datasets: List[str]) -> pd.DataFrame:
    """
    Load v3 feature files for all datasets and return a combined DataFrame
    with columns: query_id, dataset, uid, oracle_alpha, oracle_ndcg,
                  is_informative, <29 feature columns>.
    """
    rows = []
    for ds in datasets:
        path = RESULTS_DIR / ds / enc_cfg["features_v3"]
        if not path.exists():
            print(f"  [SKIP] {path} not found")
            continue
        with open(path, encoding="utf-8") as f:
            data = json.load(f)

        for qid, entry in data["queries"].items():
            feats = entry.get("features", {})
            if not all(fn in feats for fn in ALL_29):
                continue
            rows.append({
                "query_id":       str(qid),
                "dataset":        ds,
                "uid":            f"{ds}::{qid}",
                "oracle_alpha":   entry.get("oracle_alpha"),
                "oracle_ndcg":    entry.get("oracle_ndcg", 0.0),
                "is_informative": entry.get("is_informative", False),
                **{fn: feats[fn] for fn in ALL_29},
            })

    if not rows:
        return pd.DataFrame()
    df = pd.DataFrame(rows)
    df["oracle_alpha"] = pd.to_numeric(df["oracle_alpha"], errors="coerce")
    return df


# ── Retrieval ─────────────────────────────────────────────────────────────────

def run_retrieval_for_encoder(
    enc_cfg: dict,
    datasets: List[str],
    data_dir: str,
    split: str,
    top_k: int,
) -> Dict[str, dict]:
    """
    Run BM25 (once per dataset, shared across encoders) and dense retrieval
    for every dataset. Returns:
        { ds: {"bm25": {...}, "dense": {...}, "qrels": {...}} }
    """
    cache: Dict[str, dict] = {}

    for ds in datasets:
        print(f"    [{ds}] loading BEIR data...")
        download_beir_dataset(data_dir=data_dir, dataset_name=ds)
        corpus, queries, qrels = load_beir_dataset(
            data_dir=data_dir, dataset_name=ds, split=split
        )
        print(f"    [{ds}] corpus={len(corpus):,}  queries={len(queries):,}")

        t0 = time.perf_counter()
        bm25_r = run_bm25(corpus, queries, top_k=top_k)
        print(f"    [{ds}] BM25 done ({time.perf_counter() - t0:.1f}s)")

        t0 = time.perf_counter()
        cache_key = f"{ds}::{split}::{enc_cfg['model']}"
        dense_r = run_dense_retrieval(
            corpus, queries,
            model_name=enc_cfg["model"],
            top_k=top_k,
            cache_dir=enc_cfg["cache_dir"],
            cache_key=cache_key,
        )
        print(f"    [{ds}] dense done ({time.perf_counter() - t0:.1f}s)")

        cache[ds] = {"bm25": bm25_r, "dense": dense_r, "qrels": qrels}

    return cache


# ── Best static alpha on validation set ───────────────────────────────────────

def find_best_static_alpha(
    val_qids: List[str],
    bm25_r: dict,
    dense_r: dict,
    qrels: dict,
    top_k: int = 100,
) -> float:
    """Grid search for the alpha that maximises NDCG@10 on val queries."""
    val_qrels = {q: qrels[q] for q in val_qids if q in qrels}
    if not val_qrels:
        return 0.5
    bm25_sub  = {q: bm25_r[q]        for q in val_qrels if q in bm25_r}
    dense_sub = {q: dense_r.get(q, {}) for q in val_qrels}
    if not bm25_sub:
        return 0.5

    best_ndcg, best_alpha = -1.0, 0.5
    for alpha in ALPHA_GRID:
        fused = fuse_static(bm25_sub, dense_sub, alpha=alpha, top_k=top_k)
        ndcg = np.mean([
            _ndcg_at10(val_qrels[q], fused[q])
            for q in val_qrels if q in fused
        ])
        if ndcg > best_ndcg:
            best_ndcg, best_alpha = ndcg, alpha
    return best_alpha


# ── Fuse with per-query alpha ──────────────────────────────────────────────────

def fuse_with_alpha_map(
    qids: List[str],
    bm25_r: dict,
    dense_r: dict,
    alpha_map: Dict[str, float],
    top_k: int = 100,
) -> Dict[str, Dict[str, float]]:
    return {
        qid: fuse_single_query(
            bm25_r[qid], dense_r.get(qid, {}),
            alpha=float(alpha_map.get(qid, 0.5)), top_k=top_k,
        )
        for qid in qids if qid in bm25_r
    }


# ── Model training ────────────────────────────────────────────────────────────

def train_ridge(X_train: np.ndarray, y_train: np.ndarray) -> Tuple[RidgeCV, StandardScaler]:
    scaler = StandardScaler()
    Xs = scaler.fit_transform(X_train)
    model = RidgeCV(alphas=[0.001, 0.01, 0.1, 1.0, 10.0, 100.0])
    model.fit(Xs, y_train)
    return model, scaler


def train_mlp_small(
    X_train: np.ndarray, y_train: np.ndarray, scaler: StandardScaler
) -> MLPRegressor:
    Xs = scaler.transform(X_train)
    model = MLPRegressor(
        hidden_layer_sizes=(32,),
        activation="relu",
        solver="adam",
        max_iter=1000,
        early_stopping=True,
        validation_fraction=0.15,
        random_state=42,
        learning_rate_init=0.001,
        alpha=0.01,
    )
    model.fit(Xs, y_train)
    return model


# ── Feature importance ────────────────────────────────────────────────────────

def compute_feature_importance(
    enc_key: str,
    df_train: pd.DataFrame,
    df_test: pd.DataFrame,
    features: List[str],
) -> pd.DataFrame:
    """
    Train Ridge + MLP-Small on all_29 features, compute:
      - Ridge: normalized absolute coefficients
      - MLP:   permutation importance (5 repeats, r2 scoring)
    Returns a DataFrame with columns: feature, encoder, model, importance, rank
    """
    X_tr = df_train[features].values.astype(float)
    y_tr = df_train["oracle_alpha"].values.astype(float)
    X_te = df_test[features].values.astype(float)
    y_te = df_test["oracle_alpha"].values.astype(float)

    ridge, scaler = train_ridge(X_tr, y_tr)
    X_te_sc = scaler.transform(X_te)

    # Ridge coefficients
    abs_coefs = np.abs(ridge.coef_)
    norm_coefs = abs_coefs / (abs_coefs.sum() + 1e-10)

    # MLP permutation importance
    mlp = train_mlp_small(X_tr, y_tr, scaler)
    perm = permutation_importance(
        mlp, X_te_sc, y_te,
        n_repeats=5, random_state=42, scoring="r2",
    )
    perm_mean = perm.importances_mean

    rows = []
    for i, fn in enumerate(features):
        rows.append({
            "feature":    fn,
            "encoder":    enc_key,
            "model":      "ridge",
            "importance": float(norm_coefs[i]),
            "rank":       0,
        })
        rows.append({
            "feature":    fn,
            "encoder":    enc_key,
            "model":      "mlp_small",
            "importance": float(perm_mean[i]),
            "rank":       0,
        })

    df = pd.DataFrame(rows)
    for model_name in ["ridge", "mlp_small"]:
        mask = df["model"] == model_name
        df.loc[mask, "rank"] = (
            df.loc[mask, "importance"]
              .rank(ascending=False, method="min")
              .astype(int)
        )
    return df


# ── Visualization ─────────────────────────────────────────────────────────────

def plot_pearson_comparison(summary_df: pd.DataFrame, out_path: Path) -> None:
    """
    Grouped bar chart: X = feature groups, bars = encoders, Y = mean Pearson r.
    Uses Ridge results only. Includes reference lines at r=0.25 and r=0.40.
    """
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.ticker as mticker
    except ImportError:
        print("  [WARN] matplotlib not available; skipping plot")
        return

    ridge_df = summary_df[summary_df["model"] == "ridge"].copy()
    groups   = list(FEATURE_GROUPS.keys())
    enc_keys = list(ENCODER_CONFIGS.keys())

    x     = np.arange(len(groups))
    width = 0.25
    colors = {"minilm": "#2196F3", "bge": "#FF9800", "e5": "#4CAF50"}
    labels = {k: v["label"] for k, v in ENCODER_CONFIGS.items()}

    fig, ax = plt.subplots(figsize=(13, 5))

    for i, enc_key in enumerate(enc_keys):
        enc_data = ridge_df[ridge_df["encoder"] == enc_key]
        means, errs = [], []
        for fg in groups:
            row = enc_data[enc_data["feature_group"] == fg]
            means.append(float(row["mean_pearson_r"].values[0]) if not row.empty else 0.0)
            errs.append(float(row["std_pearson_r"].values[0])  if not row.empty else 0.0)
        offset = (i - 1) * width
        ax.bar(
            x + offset, means, width, yerr=errs, capsize=3,
            label=labels[enc_key], color=colors[enc_key], alpha=0.87,
            error_kw={"linewidth": 1.0},
        )

    ax.axhline(0.25, color="gray",  linestyle="--", linewidth=1.2, label="Baseline r=0.25")
    ax.axhline(0.40, color="crimson", linestyle="--", linewidth=1.2, label="Target r=0.40")

    ax.set_xticks(x)
    ax.set_xticklabels(
        [fg.replace("_", "\n") for fg in groups],
        fontsize=9, ha="center",
    )
    ax.set_ylabel("Mean Pearson r (oracle alpha vs predicted)")
    ax.set_title(
        "Phase 1: Alpha-Prediction Quality by Feature Group\n"
        "(Ridge, mean across 5 BEIR datasets, error bars = std)"
    )
    ax.legend(loc="upper left", fontsize=9)
    ax.yaxis.set_major_formatter(mticker.FormatStrFormatter("%.2f"))
    ax.grid(axis="y", alpha=0.3)
    plt.tight_layout()
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Plot saved -> {out_path}")


# ── Main experiment loop ───────────────────────────────────────────────────────

def run_experiments(
    encoders: List[str],
    datasets: List[str],
    data_dir: str,
    split: str,
    top_k: int,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:

    all_rows:    List[dict] = []
    all_imp_dfs: List[pd.DataFrame] = []

    for enc_key in encoders:
        enc_cfg = ENCODER_CONFIGS[enc_key]
        print(f"\n{'=' * 70}")
        print(f"Encoder: {enc_key}  ({enc_cfg['model']})")
        print("=" * 70)

        # ── Load v3 features ──────────────────────────────────────────────────
        df_all = load_v3_df(enc_cfg, datasets)
        if df_all.empty:
            print(f"  [SKIP] No v3 features found for {enc_key}. "
                  "Run run_post_retrieval_features.py first.")
            continue

        df_inf = df_all[df_all["is_informative"]].copy().reset_index(drop=True)
        print(f"  Informative queries: {len(df_inf)} "
              f"(out of {len(df_all)} total)")
        for ds in datasets:
            n = (df_inf["dataset"] == ds).sum()
            print(f"    {ds}: {n}")

        # ── Oracle nDCG per dataset (mean over ALL queries, from features file)
        oracle_ndcg_by_ds: Dict[str, float] = {}
        for ds in datasets:
            vals = df_all[df_all["dataset"] == ds]["oracle_ndcg"].values
            oracle_ndcg_by_ds[ds] = float(np.mean(vals)) if len(vals) > 0 else 0.0

        # ── Strategy-A split (70/15/15, same seed as existing pipeline) ───────
        print("\n  Creating 70/15/15 splits...")
        split_a = strategy_a(df_inf, random_state=42)
        train_uids = set(split_a["train_uids"])
        val_uids   = set(split_a["val_uids"])
        test_uids  = set(split_a["test_uids"])

        df_train = df_inf[df_inf["uid"].isin(train_uids)].copy()
        df_val   = df_inf[df_inf["uid"].isin(val_uids)].copy()
        df_test  = df_inf[df_inf["uid"].isin(test_uids)].copy()
        print(f"  train={len(df_train)}  val={len(df_val)}  test={len(df_test)}")

        # ── Run retrieval ─────────────────────────────────────────────────────
        print("\n  Running retrieval for all datasets...")
        retrieval = run_retrieval_for_encoder(enc_cfg, datasets, data_dir, split, top_k)

        # ── Best static alpha per dataset (from val set) ──────────────────────
        best_static: Dict[str, float] = {}
        for ds in datasets:
            if ds not in retrieval:
                continue
            val_qids_ds = df_val[df_val["dataset"] == ds]["query_id"].tolist()
            rd = retrieval[ds]
            best_static[ds] = find_best_static_alpha(
                val_qids_ds, rd["bm25"], rd["dense"], rd["qrels"], top_k
            )
            print(f"    best_static_alpha[{ds}] = {best_static[ds]:.2f}")

        # ── Pre-compute static per-query nDCG (same for all feature groups) ──
        static_pq: Dict[str, Dict[str, float]] = {}  # ds -> {qid: ndcg}
        for ds in datasets:
            if ds not in retrieval:
                continue
            rd = retrieval[ds]
            test_qids_ds = df_test[df_test["dataset"] == ds]["query_id"].tolist()
            alpha = best_static.get(ds, 0.5)
            bm25_sub  = {q: rd["bm25"][q]         for q in test_qids_ds if q in rd["bm25"]}
            dense_sub = {q: rd["dense"].get(q, {}) for q in test_qids_ds}
            fused = fuse_static(bm25_sub, dense_sub, alpha=alpha, top_k=top_k)
            static_pq[ds] = {
                q: _ndcg_at10(rd["qrels"][q], fused[q])
                for q in test_qids_ds if q in fused and q in rd["qrels"]
            }

        # ── Experiment loop: feature_group x model ────────────────────────────
        saved_models: Dict[str, dict] = {}  # for feature importance later

        for fg_name, fg_features in FEATURE_GROUPS.items():
            print(f"\n  Feature group: {fg_name}  ({len(fg_features)} features)")

            # Build train/test arrays for this feature group
            X_tr = df_train[fg_features].values.astype(float)
            y_tr = df_train["oracle_alpha"].values.astype(float)
            X_te = df_test[fg_features].values.astype(float)
            y_te = df_test["oracle_alpha"].values.astype(float)

            for model_name in ["ridge", "mlp_small"]:
                t0 = time.perf_counter()

                # Train
                if model_name == "ridge":
                    model, scaler = train_ridge(X_tr, y_tr)
                else:
                    _, scaler = train_ridge(X_tr, y_tr)  # fit scaler only
                    model = train_mlp_small(X_tr, y_tr, scaler)

                # Predict alpha for test set
                X_te_sc = scaler.transform(X_te)
                alpha_pred = np.clip(model.predict(X_te_sc), 0.0, 1.0)

                # Pearson r on combined test set
                if len(alpha_pred) > 1:
                    pearson_r_all = float(np.corrcoef(alpha_pred, y_te)[0, 1])
                    if np.isnan(pearson_r_all):
                        pearson_r_all = 0.0
                else:
                    pearson_r_all = 0.0

                # Map query UID -> predicted alpha for lookup below
                pred_alpha_map = dict(zip(df_test["query_id"].tolist(), alpha_pred.tolist()))

                # Save models from all_29 group for feature importance
                if fg_name == "all_29":
                    saved_models[model_name] = {"model": model, "scaler": scaler}

                # Per-dataset evaluation
                for ds in datasets:
                    if ds not in retrieval:
                        continue
                    rd = retrieval[ds]
                    ds_test = df_test[df_test["dataset"] == ds]
                    test_qids_ds = ds_test["query_id"].tolist()
                    if not test_qids_ds:
                        continue

                    # Per-dataset Pearson r via explicit qid mapping
                    ds_pred_list  = [pred_alpha_map.get(q, 0.5) for q in test_qids_ds]
                    ds_truth_list = ds_test["oracle_alpha"].values.tolist()

                    if len(ds_pred_list) > 1:
                        pr_ds = float(np.corrcoef(ds_pred_list, ds_truth_list)[0, 1])
                        if np.isnan(pr_ds):
                            pr_ds = 0.0
                    else:
                        pr_ds = 0.0

                    # nDCG with predicted alpha
                    pred_am = {q: pred_alpha_map[q] for q in test_qids_ds if q in pred_alpha_map}
                    fused_pred = fuse_with_alpha_map(
                        test_qids_ds, rd["bm25"], rd["dense"], pred_am, top_k
                    )
                    pred_pq = {
                        q: _ndcg_at10(rd["qrels"][q], fused_pred[q])
                        for q in test_qids_ds if q in fused_pred and q in rd["qrels"]
                    }

                    static_pq_ds = static_pq.get(ds, {})
                    common_qids  = sorted(set(pred_pq.keys()) & set(static_pq_ds.keys()))
                    if not common_qids:
                        continue

                    pred_arr   = np.array([pred_pq[q]      for q in common_qids])
                    static_arr = np.array([static_pq_ds[q] for q in common_qids])

                    mean_pred   = float(pred_arr.mean())
                    mean_static = float(static_arr.mean())
                    delta       = mean_pred - mean_static

                    if len(common_qids) >= 2:
                        _, p_val = scipy_stats.ttest_rel(pred_arr, static_arr)
                        p_val = float(p_val)
                    else:
                        p_val = 1.0

                    all_rows.append({
                        "encoder":         enc_key,
                        "dataset":         ds,
                        "feature_group":   fg_name,
                        "model":           model_name,
                        "n_features":      len(fg_features),
                        "n_test":          len(common_qids),
                        "pearson_r":       pr_ds,
                        "ndcg_predicted":  mean_pred,
                        "ndcg_static":     mean_static,
                        "ndcg_oracle":     oracle_ndcg_by_ds.get(ds, 0.0),
                        "delta_vs_static": delta,
                        "p_value":         p_val,
                    })

                elapsed = time.perf_counter() - t0
                print(
                    f"    {model_name:<10}  pearson_r={pearson_r_all:+.4f}  "
                    f"({elapsed:.1f}s)"
                )

        # ── Feature importance for all_29 ─────────────────────────────────────
        if saved_models:
            print(f"\n  Computing feature importance for all_29 ({len(ALL_29)} features)...")
            imp_df = compute_feature_importance(enc_key, df_train, df_test, ALL_29)
            all_imp_dfs.append(imp_df)

    # ── Build result DataFrames ───────────────────────────────────────────────
    full_df = pd.DataFrame(all_rows)
    if full_df.empty:
        print("\n[ERROR] No results generated.")
        return full_df, pd.DataFrame(), pd.DataFrame()

    # Summary: mean/std across datasets
    summary_rows = []
    for (enc, fg, mdl), grp in full_df.groupby(["encoder", "feature_group", "model"]):
        wins = int(((grp["ndcg_predicted"] > grp["ndcg_static"]) & (grp["p_value"] < 0.05)).sum())
        summary_rows.append({
            "encoder":             enc,
            "feature_group":       fg,
            "model":               mdl,
            "n_features":          int(grp["n_features"].iloc[0]),
            "mean_pearson_r":      float(grp["pearson_r"].mean()),
            "std_pearson_r":       float(grp["pearson_r"].std()),
            "mean_ndcg_predicted": float(grp["ndcg_predicted"].mean()),
            "mean_ndcg_static":    float(grp["ndcg_static"].mean()),
            "mean_delta":          float(grp["delta_vs_static"].mean()),
            "wins_over_static":    wins,
        })
    summary_df = pd.DataFrame(summary_rows)

    imp_df = pd.concat(all_imp_dfs, ignore_index=True) if all_imp_dfs else pd.DataFrame()
    return full_df, summary_df, imp_df


