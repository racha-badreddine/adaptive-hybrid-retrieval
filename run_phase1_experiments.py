def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Phase 1 ablation: post-retrieval features for alpha prediction."
    )
    parser.add_argument(
        "--encoders", nargs="+", default=["minilm", "bge", "e5"],
        choices=["minilm", "bge", "e5"],
    )
    parser.add_argument("--datasets", nargs="+", default=DATASETS)
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--split", default="test")
    parser.add_argument("--top-k", type=int, default=100)
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    print("\nPHASE 1 EXPERIMENTS: Post-Retrieval Feature Ablation")
    print(f"Encoders : {args.encoders}")
    print(f"Datasets : {args.datasets}")
    print(f"Feature groups  : {list(FEATURE_GROUPS.keys())}")
    print(f"Models          : ridge, mlp_small")
    print(f"Total runs      : {len(args.encoders)} x {len(FEATURE_GROUPS)} x 2 = "
          f"{len(args.encoders) * len(FEATURE_GROUPS) * 2}")
    print("=" * 70)

    t_wall = time.perf_counter()

    full_df, summary_df, imp_df = run_experiments(
        encoders=args.encoders,
        datasets=args.datasets,
        data_dir=args.data_dir,
        split=args.split,
        top_k=args.top_k,
    )

    if full_df.empty:
        print("No results to save.")
        return

    RESULTS_DIR.mkdir(exist_ok=True)

    # ── Save CSVs ─────────────────────────────────────────────────────────────
    full_path = RESULTS_DIR / "phase1_full_results.csv"
    full_df.to_csv(full_path, index=False, float_format="%.6f")
    print(f"\nFull results    -> {full_path}  ({len(full_df)} rows)")

    summary_path = RESULTS_DIR / "phase1_summary.csv"
    summary_df.to_csv(summary_path, index=False, float_format="%.6f")
    print(f"Summary         -> {summary_path}  ({len(summary_df)} rows)")

    if not imp_df.empty:
        imp_path = RESULTS_DIR / "phase1_feature_importance.csv"
        imp_df.to_csv(imp_path, index=False, float_format="%.6f")
        print(f"Feature import. -> {imp_path}  ({len(imp_df)} rows)")

    # ── Plot ──────────────────────────────────────────────────────────────────
    plot_path = RESULTS_DIR / "phase1_pearson_comparison.png"
    plot_pearson_comparison(summary_df, plot_path)

    # ── Print condensed summary table ─────────────────────────────────────────
    print(f"\n{'=' * 70}")
    print("SUMMARY  (mean Pearson r, Ridge, across datasets)")
    print("=" * 70)
    pivot = summary_df[summary_df["model"] == "ridge"].pivot_table(
        index="feature_group",
        columns="encoder",
        values="mean_pearson_r",
        aggfunc="first",
    )
    print(pivot.to_string(float_format=lambda x: f"{x:+.4f}"))

    print(f"\n{'=' * 70}")
    print("SUMMARY  (mean nDCG@10, Ridge, across datasets)")
    print("=" * 70)
    for enc_key in args.encoders:
        enc_sum = summary_df[
            (summary_df["encoder"] == enc_key) & (summary_df["model"] == "ridge")
        ][["feature_group", "mean_ndcg_predicted", "mean_ndcg_static", "mean_delta", "wins_over_static"]]
        print(f"\n  Encoder: {enc_key}")
        print(enc_sum.to_string(index=False, float_format=lambda x: f"{x:.4f}"))

    total_elapsed = time.perf_counter() - t_wall
    print(f"\nTotal runtime: {total_elapsed:.0f}s ({total_elapsed / 60:.1f} min)")


if __name__ == "__main__":
    main()
